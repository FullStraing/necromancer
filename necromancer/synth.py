"""Synthesize the replacement cloud: Meta writes a standalone server from the recovered spec + journal,
then the ORIGINAL client runs conformance scripts against it. Failures go back to Meta (repair loop).
If Meta is unavailable or never converges, a deterministic spec-driven server is emitted instead."""
from __future__ import annotations

import asyncio
import socket
import sys
from dataclasses import dataclass
from pathlib import Path

from .journal import Journal
from .llm import Meta, ModelUnavailable, extract_code
from .oracle import CONFORMANCE_SCRIPTS, OracleResult, run_client
from .spec import ProtocolSpec

SYSTEM = ("You write production-quality Python 3.12 asyncio TCP servers from reverse-engineered protocol specs. "
          "Output ONLY one ```python code block. Standard library only. No placeholders.")

FALLBACK_TEMPLATE = '''"""Resurrected Lumio cloud (deterministic spec-driven fallback, generated by Necromancer)."""
import argparse, asyncio, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from necromancer.spec import ProtocolSpec
from necromancer.spec_server import SpecServer

SPEC = ProtocolSpec.model_validate_json({spec_json!r})

async def main(port):
    srv = SpecServer(SPEC, power_rule={power_rule!r})
    await srv.start(port)
    await asyncio.Event().wait()

if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--port", type=int, default=7070)
    asyncio.run(main(ap.parse_args().port))
'''


@dataclass(frozen=True)
class SynthResult:
    path: Path
    author: str                     # "meta" | "fallback"
    rounds: int
    results: tuple[tuple[tuple[str, ...], OracleResult], ...]

    @property
    def passed(self) -> int:
        return sum(1 for _, r in self.results if r.ok)


def build_prompt(spec: ProtocolSpec, journal: Journal, power_rule: str) -> str:
    facts = "\n".join(f"- [{e.status}{'' if e.status != 'inferred' else f' p={e.confidence:.2f}'}] {e.claim}"
                      for e in journal.entries() if e.status in ("verified", "inferred") and e.confidence >= 0.5)
    return f"""Write the replacement cloud server for the "Lumio" smart lamp. The original vendor server is gone.
The original client app will connect over TCP and must work unmodified.

Recovered spec (JSON, verified from traffic):
{spec.model_dump_json(indent=1)}

Journal of verified / inferred facts:
{facts}

Power rule chosen: {power_rule}  (STATUS byte 0 = 1 iff brightness > 0 when 'brightness_nonzero')

Requirements:
- CLI: `python server.py --port N`, listen on 127.0.0.1.
- Frame: prefix bytes, type at type_off, seq u16 at seq_off ({spec.seq_endian}), payload length u16 at len_off ({spec.len_endian}),
  payload, then {spec.crc_algo} over bytes [crc_start : end-of-payload] appended {spec.crc_endian}-endian.
  CRC params: CCITT-FALSE = poly 0x1021, init 0xFFFF, no reflection, xorout 0.
- Server keeps its own seq per connection starting at {spec.seq_start}, +1 per frame sent.
- HELLO -> CHALLENGE with 4 random bytes. AUTH -> AUTH_OK (u16 random session id + u32 LE unix time).
- GET_STATUS -> STATUS (5 bytes: power, brightness, r, g, b). Default state {spec.default_status_hex}. State is per device id
  (first 8 bytes of HELLO payload) and persists across connections for the server's lifetime.
- SET_BRIGHTNESS (1 byte): if > {spec.brightness_max} reply ERROR payload [3, request seq u16 LE]; else update and ACK.
- SET_COLOR (3 bytes): update and ACK.  ACK payload = request seq u16 LE + request type u8.
- Keep handling frames until the client disconnects; never crash on disconnect.
"""


async def _wait_port(port: int, timeout: float = 6.0) -> bool:
    deadline = asyncio.get_event_loop().time() + timeout
    while asyncio.get_event_loop().time() < deadline:
        try:
            _, w = await asyncio.open_connection("127.0.0.1", port)
            w.close()
            return True
        except OSError:
            await asyncio.sleep(0.15)
    return False


def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


async def verify(path: Path) -> tuple[tuple[tuple[str, ...], OracleResult], ...]:
    port = _free_port()
    proc = await asyncio.create_subprocess_exec(sys.executable, str(path), "--port", str(port),
                                                stdout=asyncio.subprocess.DEVNULL, stderr=asyncio.subprocess.PIPE)
    try:
        if not await _wait_port(port):
            err = b""
            if proc.returncode is not None and proc.stderr:
                err = await proc.stderr.read()
            fail = OracleResult(False, f"server did not start: {err.decode()[-400:]}")
            return tuple((sc, fail) for sc in CONFORMANCE_SCRIPTS)
        return tuple([(sc, await run_client(port, sc)) for sc in CONFORMANCE_SCRIPTS])
    finally:
        if proc.returncode is None:
            proc.kill()
            await proc.wait()


async def synthesize(spec: ProtocolSpec, journal: Journal, power_rule: str, out_dir: Path, meta: Meta,
                     max_rounds: int = 3, on_round=None) -> SynthResult:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "resurrected_server.py"
    if meta.available:
        prompt = build_prompt(spec, journal, power_rule)
        for rnd in range(1, max_rounds + 1):
            try:
                code = extract_code(await meta.complete(SYSTEM, prompt, max_tokens=16000))
            except ModelUnavailable as e:
                if on_round:
                    await on_round(rnd, f"Meta unavailable: {e}")
                break
            path.write_text(code)
            results = await verify(path)
            passed = sum(1 for _, r in results if r.ok)
            if on_round:
                await on_round(rnd, f"Meta draft {rnd}: original client passes {passed}/{len(results)} scripts")
            if passed == len(results):
                return SynthResult(path, "meta", rnd, results)
            failures = "\n".join(f"- script {' '.join(sc)} -> client error: {r.error}" for sc, r in results if not r.ok)
            prompt = (build_prompt(spec, journal, power_rule) + "\n\nYour previous server:\n```python\n" + code
                      + "\n```\nThe ORIGINAL client failed on:\n" + failures + "\nFix it and return the full file.")
    path.write_text(FALLBACK_TEMPLATE.format(spec_json=spec.model_dump_json(), power_rule=power_rule))
    return SynthResult(path, "fallback", 0, await verify(path))
